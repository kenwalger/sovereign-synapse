def _embed(text: str) -> list[float]:
    """Embed text using the configured Ollama model."""
    text = text[:CHUNK_SIZE]
    try:
        vector = embed_text(EMBEDDING_MODEL, text)
    except AttributeError as e:
        raise RuntimeError(str(e)) from e
    if not vector:
        raise RuntimeError(f"Ollama returned no embeddings for model '{EMBEDDING_MODEL}'")
    return vector


def _format_hit(
    doc_id: str,
    document: str,
    metadata: dict[str, Any],
    distance: float | None,
) -> dict[str, Any]:
    """Convert a raw ChromaDB hit to a clean dict for MCP response (working memory)."""
    base_uuid = doc_id.split("#")[0]
    return {
        "synapse_id": base_uuid,
        "chunk_id": doc_id,
        "snippet": document[:600].strip() if document else "",
        "timestamp": str(metadata.get("original_timestamp", "")),
        "model": str(metadata.get("model", "")),
        "source": str(metadata.get("source", "")),
        "distance": round(distance, 4) if distance is not None else None,
    }


def _coerce_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    if isinstance(value, str):
        return value.lower() in ("true", "1", "yes")
    return bool(value)


def _forensic_receipt_from_metadata(metadata: dict[str, Any]) -> str:
    return str(
        metadata.get("forensic_receipt")
        or metadata.get("forensic_integrity")
        or "",
    )


def _prose_tax_redacted_from_metadata(metadata: dict[str, Any], body: str) -> bool:
    raw = metadata.get("prose_tax_redacted")
    if raw is not None:
        return _coerce_bool(raw)
    return not ContextCleaner.is_clean(body)


def _display_summary(text: str, max_len: int = DISPLAY_SUMMARY_MAX) -> str:
    """Short preview for hosts; never used for signature verification."""
    if not text:
        return ""
    if len(text) <= max_len:
        return text
    return text[:max_len]


def _structural_contract(
    doc_id: str,
    document: str,
    metadata: dict[str, Any],
    distance: float | None,
) -> dict[str, Any]:
    """Typed retrieval payload: metadata + distilled signal + forensic receipt_id."""
    base_uuid = doc_id.split("#")[0]
    body = document or ""
    stored_signal = metadata.get("structural_signal")
    if isinstance(stored_signal, str) and stored_signal.strip():
        canonical_signal = stored_signal.strip()
    else:
        canonical_signal = ContextCleaner.distill_signal(body)
    receipt_id = str(metadata.get("receipt_id") or metadata.get("uuid") or "")
    forensic_receipt = _forensic_receipt_from_metadata(metadata)
    prose_tax_redacted = _prose_tax_redacted_from_metadata(metadata, body)
    asset_metadata = {
        "uuid": str(metadata.get("uuid", receipt_id)),
        "receipt_id": receipt_id,
        "signature_hex": str(metadata.get("signature_hex", "")),
        "forensic_receipt": forensic_receipt,
        "prose_tax_redacted": prose_tax_redacted,
        "structural_signal": canonical_signal,
        "source": str(metadata.get("source", "")),
        "model": str(metadata.get("model", "")),
        "original_timestamp": str(metadata.get("original_timestamp", "")),
        "forensic_integrity": str(metadata.get("forensic_integrity", forensic_receipt)),
    }
    ledger_provenance = copy.deepcopy(asset_metadata)
    return {
        "contract_type": "sovereign_structural_contract",
        "receipt_id": receipt_id,
        "synapse_id": base_uuid,
        "chunk_id": doc_id,
        "metadata": asset_metadata,
        "provenance": ledger_provenance,
        "distilled_signal": canonical_signal,
        "distilled_signal_excerpt": _display_summary(canonical_signal),
        "distance": round(distance, 4) if distance is not None else None,
    }


class _ReadOnlyCollection:
    """Sovereign / Legacy Mode: forward only read API to Chroma; block mutations on the vault."""

    _MUTATING = frozenset({"add", "update", "delete", "upsert", "modify"})

    def __init__(self, inner: Any) -> None:
        self._inner = inner

    @property
    def name(self) -> str:
        return self._inner.name  # type: ignore[no-any-return]

    def count(self) -> int:
        return self._inner.count()  # type: ignore[no-any-return]

    def get(self, *args: Any, **kwargs: Any) -> Any:
        return self._inner.get(*args, **kwargs)

    def query(self, *args: Any, **kwargs: Any) -> Any:
        return self._inner.query(*args, **kwargs)

    def __getattr__(self, name: str) -> Any:
        if name in self._MUTATING:

            def _vault_read_only_violation(*_a: Any, **_k: Any) -> None:
                raise PermissionError(
                    "Sovereign Synapse vault is read-only (Legacy Mode: set "
                    "SYNAPSE_MCP_READ_ONLY=1 and/or SYNAPSE_LEGACY_MODE=1; "
                    "add/update/delete/upsert on Chroma are disabled).",
                )

            return _vault_read_only_violation
        return getattr(self._inner, name)


def _semantic_search_results(
    collection: Any,
    query: str,
    n_results: int,
    *,
    structural_contract: bool = False,
) -> list[dict[str, Any]] | str:
    """Chroma query + unique-file cap; return result dicts or an error string for JSON."""
    requested = n_results
    n_results = min(max(1, n_results), 50)
    if requested > 50:
        _logger.debug(
            "semantic search: n_results requested=%s capped to 50 (shared helper max)",
            requested,
        )
    if collection.count() == 0:
        return "empty"
    try:
        embedding = _embed(query)
    except Exception as e:
        return f"embed:{e!s}"

    fetch_n = max(n_results * 4, 10)
    try:
        raw = collection.query(
            query_embeddings=[embedding],
            n_results=min(fetch_n, collection.count()),
            include=["documents", "metadatas", "distances"],
        )
    except Exception as e:
        return f"query:{e!s}"

    hit_ids = raw.get("ids", [[]])[0]
    docs = raw.get("documents", [[]])[0]
    metas = raw.get("metadatas", [[]])[0]
    dists = raw.get("distances", [[]])[0]
    seen: set[str] = set()
    results: list[dict[str, Any]] = []
    formatter = _structural_contract if structural_contract else _format_hit
    for doc_id, doc, meta, dist in zip(hit_ids, docs, metas, dists):
        base = doc_id.split("#")[0]
        if base in seen:
            continue
        seen.add(base)
        results.append(formatter(doc_id, doc, meta or {}, dist))
        if len(results) >= n_results:
            break
    return results


def _get_collection() -> Any:
    """Return the ChromaDB collection, wrapped for read-only Legacy Mode when configured."""
    global _chroma_client, _collection
    if _collection is not None:
        return _collection

    try:
        _chroma_client = chromadb.PersistentClient(
            path=CHROMA_PATH,
            settings=Settings(anonymized_telemetry=False, allow_reset=True),
        )
        c = _chroma_client.get_collection(name=COLLECTION_NAME)
        if EFFECTIVE_READ_ONLY:
            c = _ReadOnlyCollection(c)
        _collection = c
        _logger.info(
            "Connected to ChromaDB at %s — collection '%s' (%d items)%s",
            CHROMA_PATH,
            COLLECTION_NAME,
            _collection.count(),
            " [READ-ONLY / Legacy Mode]" if EFFECTIVE_READ_ONLY else "",
        )
    except Exception as e:
        _logger.error("Failed to connect to ChromaDB: %s", e)
        raise

    return _collection


