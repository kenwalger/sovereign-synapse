mcp = FastMCP(
    name="sovereign-synapse",
    instructions=(
        "You are connected to the Sovereign Synapse vault — a local-first archive of "
        "human–AI conversation turns. Use the provided tools to retrieve semantically "
        "relevant memories, recent context, reflective synthesis, and (when a "
        "Sovereign_Persona.json exists) the Unbroken Voice / legacy persona query with "
        "forensic synapse receipts. Use get_vault_policy to see if Chroma mutations are "
        "forbidden in Legacy / read-only mode."
    ),
)


@mcp.tool()
def get_vault_policy() -> str:
    """Return read-only / Legacy Mode policy for the embedded Chroma client.

    When ``chroma_mutation_forbidden`` is true, any call to add/update/delete/upsert
    on the collection raises :class:`PermissionError`. This tool does not mutate the vault;
    it exists so hosts can surface a structured check before custom write paths.

    Returns:
        JSON with ``chroma_mutation_forbidden`` and the env toggles.
    """
    return json.dumps(
        {
            "chroma_mutation_forbidden": EFFECTIVE_READ_ONLY,
            "set_via": {
                "SYNAPSE_MCP_READ_ONLY": bool(SYNAPSE_MCP_READ_ONLY),
                "SYNAPSE_LEGACY_MODE": bool(SYNAPSE_LEGACY_MODE),
            },
            "on_mutation": {
                "error_code": "VAULT_READ_ONLY",
                "python_exception": "PermissionError",
            },
        },
        indent=2,
    )


@mcp.tool()
def search_synapses(query: str, n_results: int = 5) -> str:
    """Search the Synapse vault for semantically relevant Structural Contracts.

    Each result is a typed payload (metadata + distilled_signal + receipt_id)
    per schemas/synapse_manifest.json — not raw conversational prose.

    Args:
        query:     Natural language search query.
        n_results: Number of unique-file results to return (default 5, max 50).

    Returns:
        JSON with Structural Contract results and similarity distance.
    """
    if not query.strip():
        return json.dumps({"error": "query must not be empty"})
    if n_results < 1:
        n_results = 1
    if n_results > 50:
        n_results = 50

    try:
        collection = _get_collection()
    except Exception as e:
        return json.dumps({"error": f"ChromaDB unavailable: {e}"})

    sr = _semantic_search_results(
        collection, query, n_results, structural_contract=True
    )
    if isinstance(sr, str):
        if sr == "empty":
            return json.dumps(
                {"results": [], "message": "Vault is empty — run index first."}
            )
        if sr.startswith("embed:"):
            return json.dumps({"error": f"Embedding failed: {sr[6:]}"})
        if sr.startswith("query:"):
            return json.dumps({"error": f"ChromaDB query error: {sr[6:]}"})
        return json.dumps({"error": str(sr)})

    return json.dumps(
        {
            "results": sr,
            "query": query,
            "returned": len(sr),
            "contract_schema": "schemas/synapse_manifest.json",
        },
        indent=2,
    )


@mcp.tool()
def get_recent_context(n: int = 10) -> str:
    """Retrieve the most recently indexed synapses as working memory.

    Sorts by original_timestamp (descending) across all indexed chunks,
    deduplicates to unique source files, and returns the top N.

    Args:
        n: Number of recent unique synapses to return (default 10, max 50).

    Returns:
        JSON array of recent synapses with snippet and timestamp.
    """
    if n < 1:
        n = 1
    if n > 50:
        n = 50

    try:
        collection = _get_collection()
    except Exception as e:
        return json.dumps({"error": f"ChromaDB unavailable: {e}"})

    count = collection.count()
    if count == 0:
        return json.dumps({"results": [], "message": "Vault is empty — run index first."})

    try:
        # Fetch the entire collection so the Python-side timestamp sort
        # finds the most recent entries across the whole vault, not just
        # a partial window that would miss older-inserted recent entries.
        raw = collection.get(
            limit=count,
            include=["documents", "metadatas"],
        )
    except Exception as e:
        return json.dumps({"error": f"ChromaDB fetch error: {e}"})

    chunk_ids = raw.get("ids") or []
    docs = raw.get("documents") or []
    metas = raw.get("metadatas") or []

    items = list(zip(chunk_ids, docs, metas))

    # Sort by original_timestamp descending (string ISO sort works for our format)
    items.sort(
        key=lambda t: str(t[2].get("original_timestamp", "") if t[2] else ""),
        reverse=True,
    )

    seen: set[str] = set()
    results: list[dict[str, Any]] = []
    for doc_id, doc, meta in items:
        base = doc_id.split("#")[0]
        if base in seen:
            continue
        seen.add(base)
        results.append(_format_hit(doc_id, doc or "", meta or {}, None))
        if len(results) >= n:
            break

    return json.dumps({"results": results, "returned": len(results)}, indent=2)


@mcp.tool()
def reflect_on_memories(snippets: list[str], focus: str = "") -> str:
    """Identify strategic themes and connections across retrieved memory snippets.

    Sends the snippets to a local Ollama LLM and asks it to surface 3 themes,
    patterns, or strategic insights — functioning as an internal reflection step.

    Input is capped to the first 10 snippets and 15,000 characters to prevent
    context-window overflows.

    Args:
        snippets: List of text snippets retrieved from the vault.
        focus:    Optional guiding question or topic for the reflection.

    Returns:
        JSON with the model's reflection text and the 3 identified themes.
    """
    if not snippets:
        return json.dumps({"error": "snippets list must not be empty"})

    # Guard: cap snippet count and total character length; track both limits.
    capped_snippets = snippets[:REFLECT_MAX_SNIPPETS]
    snippets_truncated = len(snippets) > REFLECT_MAX_SNIPPETS

    combined = "\n\n---\n\n".join(s.strip() for s in capped_snippets if s.strip())
    if not combined:
        return json.dumps({"error": "all snippets were empty"})

    chars_truncated = len(combined) > REFLECT_MAX_CHARS
    combined = combined[:REFLECT_MAX_CHARS]

    focus_line = f"\n\nFocus question: {focus}" if focus.strip() else ""
    prompt = (
        "You are a senior knowledge architect reviewing a set of memory excerpts "
        "from a personal knowledge vault. Each excerpt is a snippet of a past "
        "human–AI conversation.\n\n"
        "Your task:\n"
        "1. Identify exactly 3 strategic themes or meaningful connections present "
        "across these memories.\n"
        "2. For each theme, give it a concise title and a 2-3 sentence explanation.\n"
        "3. End with a single-sentence synthesis that captures the overarching insight.\n"
        f"{focus_line}\n\n"
        "=== MEMORY EXCERPTS ===\n\n"
        f"{combined}\n\n"
        "=== END EXCERPTS ===\n\n"
        "Respond in plain text. Be precise and strategic."
    )

    try:
        response = ollama.chat(
            model=REFLECT_LLM,
            messages=[{"role": "user", "content": prompt}],
        )
        reflection_text: str = response.message.content or ""
    except Exception as e:
        return json.dumps(
            {
                "error": f"Ollama LLM call failed: {e}",
                "hint": f"Ensure '{REFLECT_LLM}' is available: ollama pull {REFLECT_LLM}",
            }
        )

    # Best-effort: extract 3 theme titles from the response (lines with leading digits)
    theme_lines = re.findall(r"(?:^|\n)\s*(?:\d+[.)]\s*)(.+)", reflection_text)
    themes = [t.strip() for t in theme_lines[:3]] if theme_lines else []

    return json.dumps(
        {
            "reflection": reflection_text,
            "themes": themes,
            "snippet_count": len(capped_snippets),
            "truncated": snippets_truncated or chars_truncated,
            "truncation_reason": (
                "snippet_count_and_chars" if snippets_truncated and chars_truncated
                else "snippet_count" if snippets_truncated
                else "chars" if chars_truncated
                else None
            ),
            "llm": REFLECT_LLM,
        },
        indent=2,
    )


@mcp.tool()
def query_legacy_persona(query: str, n_evidence: int = 8) -> str:
    """Unbroken Voice: answer *as* the author using *Sovereign_Persona.json* + Forensic Receipts.

    Semantically searches the Chroma vault for the query, attaches the top *N* unique-synapse
    receipts to the user message, and calls a local Ollama model with
    ``legacy_system_prompt`` as the system context. The reply must ground opinions in
    cited ``synapse_id`` values. All runs locally (no cloud). Requires a generated persona
    file; see ``unbroken_voice.py``.

    Args:
        query: Question to pose to the legacy persona.
        n_evidence: Max unique files to retrieve as evidence (1–20, default 8).

    Returns:
        JSON with ``answer``, ``forensic_receipts`` (synapse_id, chunk_id, snippet_excerpt), and
        model metadata, or a structured error.
    """
    if not query.strip():
        return json.dumps({"error": "query must not be empty"})
    try:
        ne = int(n_evidence)
    except (TypeError, ValueError):
        ne = 8
    ne = min(max(1, ne), 20)

    persona_path = Path(PERSONA_PATH)
    if not persona_path.is_file():
        return json.dumps(
            {
                "error": f"Sovereign_Persona.json not found at {persona_path}",
                "hint": "From the repo root: python unbroken_voice.py -o vault/Sovereign_Persona.json",
            }
        )
    try:
        persona: dict[str, Any] = json.loads(persona_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        return json.dumps({"error": f"Could not read persona JSON: {e}"})
    system_prompt = (persona.get("legacy_system_prompt") or "").strip()
    if not system_prompt:
        return json.dumps(
            {
                "error": "legacy_system_prompt is empty in Sovereign_Persona.json",
                "hint": "Re-run unbroken_voice.py with an indexed vault and Ollama up.",
            }
        )

    try:
        collection = _get_collection()
    except Exception as e:
        return json.dumps({"error": f"ChromaDB unavailable: {e}"})

    sr = _semantic_search_results(collection, query, ne)
    if isinstance(sr, str):
        if sr == "empty":
            return json.dumps(
                {
                    "error": "Vault is empty; cannot build forensic receipts.",
                    "hint": "Index synapses, then re-run the legacy query.",
                }
            )
        if sr.startswith("embed:"):
            return json.dumps({"error": f"Embedding failed: {sr[6:]}"})
        if sr.startswith("query:"):
            return json.dumps({"error": f"ChromaDB query error: {sr[6:]}"})
        return json.dumps({"error": str(sr)})

    evidence_blocks: list[str] = []
    receipts_out: list[dict[str, Any]] = []
    for r in sr:
        sid = r["synapse_id"]
        sn = r.get("snippet", "") or ""
        evidence_blocks.append(
            f"**Forensic receipt** `synapse_id={sid}` `chunk_id={r.get('chunk_id', '')}`\n"
            f"```\n{sn}\n```\n"
        )
        receipts_out.append(
            {
                "synapse_id": sid,
                "chunk_id": r.get("chunk_id", ""),
                "snippet_excerpt": sn,
                "original_timestamp": r.get("timestamp", ""),
                "receipt_id": "",
            }
        )

    user_content = (
        f"**Question (answer in the author's voice, citing synapse_id for claims):**\n{query}\n\n"
        "**Retrieved evidence from the local vault (ground your answer in these only):**\n\n"
    ) + "\n\n".join(evidence_blocks)
    system_full = (
        system_prompt
        + "\n\n---\n**Navigator protocol:** Cite the relevant `synapse_id` when attributing a "
        "position. If a topic is not covered, say you lack evidence in that voice—do not fabricate."
    )
    try:
        response = ollama.chat(
            model=LEGACY_PERSONA_LLM,
            messages=[
                {"role": "system", "content": system_full},
                {"role": "user", "content": user_content},
            ],
        )
        answer = (response.message.content or "").strip()
    except Exception as e:
        return json.dumps(
            {
                "error": f"Ollama LLM call failed: {e}",
                "hint": f"Ensure '{LEGACY_PERSONA_LLM}' is available: ollama pull {LEGACY_PERSONA_LLM}",
            }
        )

    excerpt = system_prompt[:200] + "..." if len(system_prompt) > 200 else system_prompt
    return json.dumps(
        {
            "answer": answer,
            "forensic_receipts": receipts_out,
            "persona_urn": str(persona.get("id", "")),
            "legacy_system_prompt_excerpt": excerpt,
            "llm": LEGACY_PERSONA_LLM,
        },
        indent=2,
    )


